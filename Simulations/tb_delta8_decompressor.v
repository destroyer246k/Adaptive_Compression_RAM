
`timescale 1ns/1ps

module tb_delta8_decompressor;

    reg clk;
    reg rst;

    reg [127:0] packed_data;
    reg packed_valid;

    wire [7:0] data_out;
    wire valid_out;
    wire done;

    reg [7:0] expected [0:15];

    integer output_count;
    integer errors;

    // Clock
    always #5 clk = ~clk;

    delta8_decompressor uut (
        .clk(clk),
        .rst(rst),

        .packed_data(packed_data),
        .packed_valid(packed_valid),

        .data_out(data_out),
        .valid_out(valid_out),
        .done(done)
    );

    initial begin

        clk = 0;
        rst = 1;

        packed_data  = 128'd0;
        packed_valid = 1'b0;

        output_count = 0;
        errors = 0;

        // Expected original block
        expected[0]  = 8'd100;
        expected[1]  = 8'd150;
        expected[2]  = 8'd120;
        expected[3]  = 8'd200;
        expected[4]  = 8'd190;
        expected[5]  = 8'd210;
        expected[6]  = 8'd205;
        expected[7]  = 8'd220;
        expected[8]  = 8'd200;
        expected[9]  = 8'd210;
        expected[10] = 8'd230;
        expected[11] = 8'd225;
        expected[12] = 8'd240;
        expected[13] = 8'd230;
        expected[14] = 8'd250;
        expected[15] = 8'd245;

        // Reset
        #12;
        rst = 1'b0;

        /*
        Packed data generated by DELTA8 packer:

        FB 14 F6 0F FB 14 0A EC
        0F FB 14 F6 50 E2 32 64

        Packed_data:
        128'hFB14F60FFB140AEC0FFB14F650E23264
        */

        packed_data = 128'hFB14F60FFB140AEC0FFB14F650E23264;

        // Send packed block
        @(negedge clk);
        packed_valid = 1'b1;

        @(negedge clk);
        packed_valid = 1'b0;

        // Wait for completion
        wait(done);

        #1;

        $display("");
        $display("DELTA8 DECOMPRESSOR TEST");
        $display("-------------------------");
        $display("");

        if (output_count == 16 && errors == 0) begin
            $display("Output bytes = %0d", output_count);
            $display("Errors       = %0d", errors);
            $display("DELTA8 DECOMPRESSOR TEST PASS");
        end
        else begin
            $display("Output bytes = %0d", output_count);
            $display("Errors       = %0d", errors);
            $display("DELTA8 DECOMPRESSOR TEST FAIL");
        end

        $finish;
    end


    // Check decompressed bytes
    always @(posedge clk) begin

        if (valid_out) begin

            $display(
                "Byte %0d | Got = %0d | Expected = %0d",
                output_count,
                data_out,
                expected[output_count]
            );

            if (data_out != expected[output_count]) begin
                errors = errors + 1;
            end

            output_count = output_count + 1;
        end

    end

endmodule